// The page's pinned values come from the console's own config, firmware/quorum_cfg.py (JSON on
// purpose), so the page and the console agree on the passkey factory and the services. build.mjs and
// test.mjs call this before anything imports src/config.gen.mjs (which is generated, not committed).
import { readFileSync, writeFileSync } from "node:fs";

export function writeConfig() {
  const src = readFileSync(new URL("../firmware/quorum_cfg.py", import.meta.url), "utf8");
  const cfg = JSON.parse(src.slice(src.indexOf("{", src.indexOf("CFG ="))));
  const pick = { signer: cfg.signer, services: cfg.services, chains: cfg.chains, delegates: cfg.delegates, batchers: cfg.batchers,
                 contracts: cfg.contracts, sameAs: cfg.sameAs };
  const out = `// Generated by web/config.mjs from firmware/quorum_cfg.py. Do not edit.\nexport const CFG = ${JSON.stringify(pick, null, 1)};\n`;
  writeFileSync(new URL("src/config.gen.mjs", import.meta.url), out);
  return pick;
}
