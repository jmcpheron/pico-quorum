"""Write hardware/picoquorum-key/picoquorum-key.kicad_sch from circuit.py.

  python3 tools/gen/gen_sch.py [--force]

Every pin gets a net label at its tip (or a no-connect flag); there are no wires. The sheet is
meant to be read section by section. Once the schematic has been edited by hand in KiCad, it is the
truth: this script refuses to overwrite a schematic it didn't write unless --force is given.
"""
import os
import sys
import uuid

sys.path.insert(0, os.path.dirname(__file__))
from sexp import QStr, dumps, find_all  # noqa: E402
from kicadlib import load_symbol, pins  # noqa: E402
import circuit  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "hardware/picoquorum-key/picoquorum-key.kicad_sch")
PROJECT = "picoquorum-key"
MARK = "generated by tools/gen/gen_sch.py"
NS = uuid.UUID("6f1c3a52-2c55-4b8e-9d0e-5c0a3e3f5a11")


def uid(*key):
    """Stable UUIDs so regenerating doesn't churn every line (and keeps the board's links)."""
    return QStr(str(uuid.uuid5(NS, "/".join(str(k) for k in key))))


def r(v):
    return round(v, 4)


def font(size=1.27):
    return ["font", ["size", size, size]]


def prop(name, value, x, y, hide=False, justify=None, angle=0):
    eff = ["effects", font()]
    if justify:
        eff.append(["justify"] + justify)
    if hide:
        eff.append(["hide", "yes"])
    return ["property", QStr(name), QStr(value), ["at", r(x), r(y), angle], eff]


def main():
    force = "--force" in sys.argv
    if os.path.exists(OUT) and not force and MARK not in open(OUT).read():
        sys.exit(f"{OUT} wasn't written by this script; pass --force to overwrite it")

    root_uuid = uid("root")
    lib_ids = sorted({p.lib_id for p in circuit.PARTS})
    lib_syms = {lid: load_symbol(lid) for lid in lib_ids}

    items = []
    tips = {}            # (x, y) -> (ref, pin, net) to catch accidental shorts
    errors = []
    pwr_n = 0

    for part in circuit.PARTS:
        sym = lib_syms[part.lib_id]
        X, Y = part.pos
        spins = pins(sym)
        numbers = {p[0] for p in spins}
        missing = numbers - set(part.nets)
        extra = set(part.nets) - numbers
        if missing:
            errors.append(f"{part.ref}: pins without a net or NC: {sorted(missing)}")
        if extra:
            errors.append(f"{part.ref}: nets for pins the symbol doesn't have: {sorted(extra)}")

        # bounding box of the pins, screen coordinates
        xs = [X + p[3] for p in spins] or [X]
        ys = [Y - p[4] for p in spins] or [Y]
        sides = {p[5] for p in spins}
        is_power = part.ref.startswith("#")

        # reference / value placement: a side with no pins
        if not spins or 180 not in sides:      # no pins on the right
            fx, fy, just = max(xs) + 2.54, Y, ["left"]
        elif 0 not in sides:                   # no pins on the left
            fx, fy, just = min(xs) - 2.54, Y, ["right"]
        else:
            fx, fy, just = min(xs), min(ys) - 6.35, ["left"]
        if part.lib_id in ("Device:R", "Device:C"):
            fx, fy, just = X + 2.54, Y, ["left"]

        props = [
            prop("Reference", part.ref, fx, fy - 1.27, hide=is_power, justify=just),
            prop("Value", part.value, fx, fy + 1.27, justify=just),
            prop("Footprint", part.footprint, X, Y, hide=True),
            prop("Datasheet", "~", X, Y, hide=True),
            prop("Description", part.note, X, Y, hide=True),
        ]
        if not is_power:
            props.append(prop("LCSC", part.lcsc, X, Y, hide=True))
            props.append(prop("MPN", part.mpn or part.value, X, Y, hide=True))

        node = ["symbol", ["lib_id", QStr(part.lib_id)], ["at", r(X), r(Y), 0], ["unit", 1],
                ["exclude_from_sim", "no"], ["in_bom", "yes" if part.in_bom else "no"],
                ["on_board", "yes" if part.on_board else "no"], ["dnp", "yes" if part.dnp else "no"],
                ["uuid", uid("sym", part.ref)]] + props
        for num in sorted(numbers):
            node.append(["pin", QStr(num), ["uuid", uid("pin", part.ref, num)]])
        node.append(["instances", ["project", QStr(PROJECT),
                                   ["path", QStr("/" + root_uuid), ["reference", QStr(part.ref)], ["unit", 1]]]])
        items.append(node)

        # labels / no-connects at every pin tip
        done = set()
        for num, name, ptype, px, py, ang in spins:
            tx, ty = r(X + px), r(Y - py)
            net = part.nets.get(num, None)
            key = (tx, ty)
            if key in tips and tips[key][0] != part.ref:
                errors.append(f"{part.ref}.{num} lands on {tips[key][0]}.{tips[key][1]} at {key}")
            if key in tips and tips[key][0] == part.ref and tips[key][2] != net:
                errors.append(f"{part.ref}.{num} stacked with pin {tips[key][1]} but on a different net")
            tips[key] = (part.ref, num, net)
            if key in done:
                continue
            done.add(key)
            if net is None:
                items.append(["no_connect", ["at", tx, ty], ["uuid", uid("nc", part.ref, num)]])
                continue
            # label points away from the body: pin angle 0 = left side, 180 = right, 90 = bottom, 270 = top
            # global labels so nets are named "GND", not "/GND", on the board
            la, lj = {0: (180, ["right"]), 180: (0, ["left"]), 90: (270, ["right"]), 270: (90, ["left"])}[ang]
            items.append(["global_label", QStr(net), ["shape", "passive"], ["at", tx, ty, la],
                          ["fields_autoplaced", "yes"], ["effects", font(), ["justify"] + lj],
                          ["uuid", uid("label", part.ref, num)],
                          ["property", QStr("Intersheetrefs"), QStr("${INTERSHEET_REFS}"), ["at", tx, ty, 0],
                           ["effects", font(), ["justify", "left"], ["hide", "yes"]]]])

    for i, ((x, y), text) in enumerate(circuit.NOTES):
        items.append(["text", QStr(text), ["exclude_from_sim", "no"], ["at", r(x), r(y), 0],
                      ["effects", ["font", ["size", 1.778, 1.778], ["bold", "yes"]], ["justify", "left", "top"]],
                      ["uuid", uid("note", i)]])

    if errors:
        print("\n".join(errors))
        sys.exit(1)

    sch = ["kicad_sch", ["version", 20250114], ["generator", QStr("eeschema")],
           ["generator_version", QStr("9.0")], ["uuid", root_uuid], ["paper", QStr("A3")],
           ["title_block", ["title", QStr("picoquorum-key: one owner of a Safe multisig")],
            ["date", QStr("2026-10-23")], ["rev", QStr("A")],
            ["comment", 1, QStr("Pins: docs/PINS.md (profile picoquorum-key). Circuits: docs/DESIGN.md.")],
            ["comment", 2, QStr("U1 and the key port (section 7) are DNP for assembly: hand-fitted. " + MARK + ".")]],
           ["lib_symbols"] + [lib_syms[l] for l in lib_ids]] + items + [
           ["sheet_instances", ["path", QStr("/"), ["page", QStr("1")]]],
           ["embedded_fonts", "no"]]
    with open(OUT, "w") as f:
        f.write(dumps(sch) + "\n")
    nets = {n for p in circuit.PARTS for n in p.nets.values() if n}
    print(f"wrote {OUT}: {len(circuit.PARTS)} symbols, {len(nets)} nets")


if __name__ == "__main__":
    main()
